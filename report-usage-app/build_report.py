def shade(cell, hex_fill="EDEDED"):
    tcPr = cell._tc.get_or_add_tcPr()
    el = OxmlElement("w:shd")
    el.set(qn("w:val"), "clear")
    el.set(qn("w:color"), "auto")
    el.set(qn("w:fill"), hex_fill)
    tcPr.append(el)


def set_cell(cell, text, bold=False, size=TABLE_SIZE, align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.space_after = Pt(1)
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = "Calibri"


def add_table(doc, headers, rows, widths, header_fill="EDEDED",
              first_col_bold=False, size=TABLE_SIZE):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    trPr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    th.set(qn("w:val"), "true")
    trPr.append(th)
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        set_cell(c, h, bold=True, size=size)
        shade(c, header_fill)
        c.width = Cm(widths[i])
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            set_cell(cells[i], str(val), bold=(first_col_bold and i == 0), size=size)
            cells[i].width = Cm(widths[i])
    doc.add_paragraph()
    return t


def add_bug_table(doc, bugs, widths=(4.4, 12.6)):
    """Один блок «Поле / Значение» на все баги (как в примере)."""
    t = doc.add_table(rows=1, cols=2)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0].cells
    set_cell(hdr[0], "Поле", bold=True)
    set_cell(hdr[1], "Значение", bold=True)
    for c in hdr:
        shade(c)
        c.width = Cm(widths[0] if c is hdr[0] else widths[1])

    for bug in bugs:
        row = t.add_row()
        merged = row.cells[0].merge(row.cells[1])
        set_cell(merged, bug["title"], bold=True)
        shade(merged, "F4F4F4")
        for label, value in bug["fields"]:
            r = t.add_row()
            set_cell(r.cells[0], label, bold=True)
            set_cell(r.cells[1], value)
            r.cells[0].width = Cm(widths[0])
            r.cells[1].width = Cm(widths[1])
    doc.add_paragraph()
    return t


def add_figure(doc, key, filename, caption, width_cm=16.5):
    _fig["n"] += 1
    assert FIG[key] == _fig["n"], f"{key}: ожидался рисунок {FIG[key]}, вставлен {_fig['n']}"
    path = os.path.join(IMG, filename)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(path, width=Cm(width_cm))

    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(10)
    run = cap.add_run(f"Рисунок {_fig['n']} — {caption}")
    run.italic = True
    run.font.size = Pt(CAPTION_SIZE)
    return _fig["n"]


def para(doc, text, bold_lead=None, indent=True):
    p = doc.add_paragraph()
    if bold_lead:
        r = p.add_run(bold_lead + " ")
        r.bold = True
    p.add_run(("\t" if indent and not bold_lead else "") + text)
    return p


def bullet(doc, text):
    p = doc.add_paragraph(text, style="List Bullet")
    p.paragraph_format.space_after = Pt(2)
    return p


def page_number_footer(section):
    """Номер страницы как в примере: по центру, серый, 9 пт, поле PAGE."""
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    def styled_run():
        r = p.add_run()
        r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
        return r

    r = styled_run()
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "begin"); r._r.append(e)
    r = styled_run()
    e = OxmlElement("w:instrText"); e.set(qn("xml:space"), "preserve"); e.text = "PAGE"
    r._r.append(e)
    r = styled_run()
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "separate"); r._r.append(e)
    r = styled_run()
    r.add_text("1")
    r = styled_run()
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "end"); r._r.append(e)


